CREATE TABLE IF NOT EXISTS users(
  id SERIAL PRIMARY KEY, name TEXT NOT NULL,
  role TEXT NOT NULL CHECK (role IN ('admin','chief','content','editor','proof')),
  hash TEXT NOT NULL, must INTEGER NOT NULL DEFAULT 0, created_at TIMESTAMPTZ NOT NULL DEFAULT now());
CREATE TABLE IF NOT EXISTS sessions(
  id TEXT PRIMARY KEY, uid INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE, exp BIGINT NOT NULL);
CREATE INDEX IF NOT EXISTS ix_sessions_uid ON sessions(uid);
CREATE TABLE IF NOT EXISTS items(
  id INTEGER PRIMARY KEY, type TEXT NOT NULL, sec INTEGER NOT NULL DEFAULT 0, st TEXT NOT NULL,
  date TEXT, data TEXT NOT NULL, updated_at TIMESTAMPTZ NOT NULL DEFAULT now());
CREATE INDEX IF NOT EXISTS ix_items ON items(type, st, date);
CREATE TABLE IF NOT EXISTS comments(
  id INTEGER PRIMARY KEY, item INTEGER NOT NULL REFERENCES items(id) ON DELETE CASCADE,
  name TEXT NOT NULL, text TEXT NOT NULL, st TEXT NOT NULL, created_at TIMESTAMPTZ NOT NULL DEFAULT now());
CREATE INDEX IF NOT EXISTS ix_comments_item ON comments(item);
CREATE TABLE IF NOT EXISTS newsletter(email TEXT PRIMARY KEY, created TEXT);
CREATE TABLE IF NOT EXISTS kv(k TEXT PRIMARY KEY, v TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS visits(day TEXT PRIMARY KEY, n INTEGER NOT NULL DEFAULT 0);
CREATE TABLE IF NOT EXISTS views(item INTEGER PRIMARY KEY REFERENCES items(id) ON DELETE CASCADE, n INTEGER NOT NULL DEFAULT 0);
CREATE TABLE IF NOT EXISTS sources(host TEXT PRIMARY KEY, n INTEGER NOT NULL DEFAULT 0);
CREATE TABLE IF NOT EXISTS logs(id SERIAL PRIMARY KEY, t TEXT, x TEXT);
